-- =====================================================================
--  EXPORTAR EL ESQUEMA DE LA BASE DE DATOS (Servicios Autos LED)
--
--  Para qué: las tablas, las funciones (registrar_venta, registrar_compra,
--  anular_venta, anular_compra, tasa_vigente…), los triggers y las políticas
--  RLS viven SOLO dentro de Supabase. Este script las convierte en texto
--  para guardarlas en  supabase/schema.sql  dentro del repositorio.
--
--  Cómo usarlo:
--    1. Supabase → SQL Editor → New query → pega TODO este archivo → Run.
--    2. Sale una sola celda (columna "esquema"). Haz clic en ella → copia.
--    3. Pega el contenido en  supabase/schema.sql  y haz commit.
--    Repite cada vez que cambies algo en la base de datos.
--
--  Solo LEE el catálogo de PostgreSQL: no modifica nada ni exporta datos.
-- =====================================================================
with
tablas as (
  select c.oid, c.relname, c.relrowsecurity
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'p')
),
-- 1) CREATE TABLE con columnas, tipos, defaults y NOT NULL
ddl_tablas as (
  select 10 as orden, t.relname as nombre,
         format(E'create table if not exists public.%I (\n%s\n);', t.relname,
           string_agg(
             format('  %I %s', a.attname, format_type(a.atttypid, a.atttypmod))
             || case a.attidentity when 'a' then ' generated always as identity'
                                   when 'd' then ' generated by default as identity' else '' end
             || coalesce(' default ' || pg_get_expr(d.adbin, d.adrelid), '')
             || case when a.attnotnull then ' not null' else '' end,
             E',\n' order by a.attnum)) as ddl
  from tablas t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  group by t.relname
),
-- 2) Restricciones: primero PK / UNIQUE / CHECK, luego las FOREIGN KEY
ddl_restricciones as (
  select case co.contype when 'f' then 30 else 20 end, t.relname || '.' || co.conname,
         format('alter table public.%I add constraint %I %s;', t.relname, co.conname,
                pg_get_constraintdef(co.oid))
  from tablas t
  join pg_constraint co on co.conrelid = t.oid
  where co.contype in ('p', 'u', 'c', 'f', 'x')
),
-- 3) Índices que no vienen de una restricción
ddl_indices as (
  select 40, i.indexname, i.indexdef || ';'
  from pg_indexes i
  where i.schemaname = 'public'
    and not exists (select 1 from pg_constraint co where co.conname = i.indexname)
),
-- 4) Vistas
ddl_vistas as (
  select 50, c.relname,
         format(E'create or replace view public.%I as\n%s', c.relname, pg_get_viewdef(c.oid, true))
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'
),
-- 5) Funciones y procedimientos propios (excluye los que trae una extensión)
ddl_funciones as (
  select 60, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
         pg_get_functiondef(p.oid) || ';'
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend dp
                    where dp.objid = p.oid and dp.deptype = 'e')
),
-- 6) Triggers
ddl_triggers as (
  select 70, t.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
  from tablas t
  join pg_trigger tg on tg.tgrelid = t.oid and not tg.tgisinternal
),
-- 7) Seguridad: RLS activado/desactivado por tabla
ddl_rls as (
  select 80, relname,
         format('alter table public.%I %s row level security;', relname,
                case when relrowsecurity then 'enable' else 'disable' end)
  from tablas
),
-- 8) Políticas RLS
ddl_politicas as (
  select 90, tablename || '.' || policyname,
         format('create policy %I on public.%I as %s for %s to %s%s%s;',
                policyname, tablename, lower(permissive), lower(cmd),
                array_to_string(roles, ', '),
                coalesce(E'\n  using (' || qual || ')', ''),
                coalesce(E'\n  with check (' || with_check || ')', ''))
  from pg_policies
  where schemaname = 'public'
),
todo as (
  select * from ddl_tablas
  union all select * from ddl_restricciones
  union all select * from ddl_indices
  union all select * from ddl_vistas
  union all select * from ddl_funciones
  union all select * from ddl_triggers
  union all select * from ddl_rls
  union all select * from ddl_politicas
)
select
  '-- Esquema de Servicios Autos LED · exportado el '
  || to_char(now() at time zone 'America/Caracas', 'DD/MM/YYYY HH24:MI') || E' (hora de Venezuela)\n'
  || E'-- Generado con supabase/exportar_esquema.sql. No contiene datos.\n\n'
  || string_agg(ddl, E'\n\n' order by orden, nombre) as esquema
from todo;
